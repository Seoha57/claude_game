/** 숫자를 {n}으로 바꿔 조각 사전을 찾고, 번역문에 원래 숫자를 되꽂는다. */
export function tDesc(korean: string): string {
  if (getLang() === 'ko') return korean;
  const parts = korean.split(/(?<=[.!])\s*/).filter((s) => s.length > 0);
  return parts
    .map((part) => {
      const nums: string[] = [];
      const key = part.replace(/\d+/g, (m) => { nums.push(m); return '{n}'; });
      const en = FRAGMENTS[key];
      if (!en) return part;
      let i = 0;
      return en.replace(/\{n\}/g, () => nums[i++] ?? '?');
    })
    .join(' ');
}
